(function () {
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const enc = encodeURIComponent;

  function songCard(s) {
    return `<div class="music-card" data-audio="${esc(s.audio)}">
      <div class="image-box" role="button" tabindex="0" aria-label="Play ${esc(s.title)} by ${esc(s.artist)}">
        <img src="${esc(s.img)}" alt="${esc(s.title)} cover art" loading="lazy" />
        <button type="button" class="play-btn" tabindex="-1" aria-hidden="true"><i class="fa-solid fa-play"></i></button>
      </div>
      <h3><a href="#song/${enc(s.audio)}">${esc(s.title)}</a></h3>
      <p><a href="#artist/${enc(s.artist)}">${esc(s.artist)}</a></p>
    </div>`;
  }

  function artistCard(a) {
    return `<div class="artist-card" role="link" tabindex="0" aria-label="${esc(a.name)}, artist">
      <img src="${esc(a.img)}" alt="" loading="lazy" />
      <h3>${esc(a.name)}</h3>
      <p>Artist</p>
    </div>`;
  }

  function chartCard(c) {
    const title = c.lines.map(esc).join("<br />") + (c.accent ? (c.lines.length ? "<br />" : "") + "<span>" + esc(c.accent) + "</span>" : "");
    const name = c.lines.concat(c.accent ? [c.accent] : []).join(" ");
    return `<div class="chart-card ${esc(c.cls)}" role="link" tabindex="0" aria-label="${esc(name)}, ${esc(c.sub)}">
      <h1>${title}</h1>
      <p>${esc(c.sub)}</p>
      <button type="button" class="play-btn" aria-label="Play ${esc(name)}"><i class="fa-solid fa-play" aria-hidden="true"></i></button>
    </div>`;
  }

  const D = window.BB_DATA;
  const fill = (key, list, fn) => {
    const el = document.querySelector('[data-list="' + key + '"]');
    if (el) el.innerHTML = list.map(fn).join("");
  };
  fill("trending", D.trending, songCard);
  fill("albums", D.albums, songCard);
  fill("artists", D.artists, artistCard);
  fill("charts", D.charts, chartCard);
})();